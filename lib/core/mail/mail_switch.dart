/// 邮箱能力的**总开关**（0.83.0）—— 默认关，开启后才有工具。
///
/// ---------------------------------------------------------------------------
/// 为什么非要补这一层（隐私审计 P0-1）
/// ---------------------------------------------------------------------------
/// 0.64.0 把邮箱做成五个工具时，唯一的门是「**有没有绑定账号**」——
/// 绑了号 ⇒ 工具无条件注册 ⇒ 分身立刻能读信、能代发。也就是说：
/// 主人**只做了一次"绑账号"（那是配置动作，不是授权动作）**，就把整箱邮件
/// 的读权限交出去了，而且**界面上没有一处能把它关掉**（"能开不能关"）。
/// 0.82.0 又在试用期把邮箱放行，暴露面进一步变大 ⇒ 总开关成了必补项。
///
/// 三条纪律：
///   ① **默认关**：键不存在 = 关。隐私相关的能力一律"用户主动开"，
///      不允许"装好就能用"（与通知 / 语音播报同一口径）。
///   ② **关 = 不注册**，不是"注册了再拒绝"。模型在工具表里根本看不见
///      这五个工具，也就不存在"模型偏要调、我们再拦一道"的攻防。
///      关掉的瞬间立刻从注册表摘除（`AgentService.setMailEnabled`）。
///   ③ **键名与默认值语义只此一处**：读取方（`initAgent`）与写入方
///      （设置页）都走 `MailSwitch.mailEnabledPrefKey` / `MailSwitch.resolve`，不许各写各的。
///
/// ★ 本文件**刻意零依赖**（不 import Flutter / shared_preferences）：
///   真实读写散在宿主的 `SharedPreferences` 调用点，而"键名 + 默认语义"
///   必须能被 `tool/verify_mail_switch.dart` 用 `dart run` 直接断言
///   （本仓 `flutter test` 在本机被安全策略挡住，见 R19.4）。
library;

/// 邮箱工具组总开关的持久化键（布尔）。
abstract final class MailSwitch {
  /// ★★ 常量名必须**全局唯一**（本仓踩过两次）：
  ///   `tool/verify_data_keys.dart` 的键解析建的是**全局**「常量名 → 字面量」表，
  ///   **同名即歧义 ⇒ 两处都被降级成"动态键"**，那条守卫会被永久蒙住。
  ///     · `LanguageController.prefKey` / `ModeController.modePrefKey` 已各占一个；
  ///     · **叫 `key` 也不行** —— `db_helper.dart` / `radar_service.dart` 里
  ///       早有同名常量（实测：本键初版就叫 `key`，`verify_data_keys`
  ///       立刻报"登记表过期项已消失"）。
  ///   新键常量一律取**全局唯一名**。
  static const String mailEnabledPrefKey = 'mail_enabled';

  /// **默认关**：键不存在（`null`）= 关。
  ///
  /// 只有显式写过 `true` 才算开——老用户升级后邮箱能力**不会**自动获得，
  /// 必须由他在设置里亲手打开一次（隐私能力的默认态纪律）。
  static bool resolve(bool? stored) => stored == true;
}
